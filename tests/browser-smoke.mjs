import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
import {writeFile,mkdir} from 'node:fs/promises';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const base=process.env.ECHOTRACE_URL||'http://127.0.0.1:4173/';
await mkdir(resolve(root,'test-output'),{recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH,headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.goto(base);
await page.getByRole('button',{name:'Prøv syntetiske klokker'}).click();
await page.locator('.sound-card').first().waitFor({timeout:60000});
await page.locator('.source-panel .source-credit').waitFor({timeout:10000});
console.log('Bells:',await page.locator('.sound-card').allTextContents());
if(!(await page.locator('.sound-card').nth(1).textContent()).includes('Mulig lydtype'))throw Error('Bell screening missing');
await page.screenshot({path:root+'/test-output/multi-sound-desktop.png',fullPage:true});
await page.locator('.source-panel summary').click();
await page.locator('[name="source-query"]').fill('Åsted');await page.getByRole('button',{name:'Find kilder',exact:true}).click();
const option=await page.locator('[name="reference-source"] option').nth(1).getAttribute('value');
await page.locator('[name="reference-source"]').selectOption(option);
await page.locator('[name="reference-provenance"]').fill('UI test fixture · synthetic');await page.locator('[name="reference-license"]').fill('CC0');await page.locator('[name="reference-consent"]').check();
await page.getByRole('button',{name:'Åbn referenceoptagelse og gem reference'}).click();
const download=page.waitForEvent('download');
await page.locator('#reference-input').setInputFiles(root+'/public/assets/synthetic-bells.wav');
const downloaded=await download;const referencePath=await downloaded.path();
await page.getByText('Referencer, der ligner din optagelse',{exact:true}).waitFor();
await page.locator('.source-matches article').waitFor({timeout:30000});
console.log('Reference import/export: works (test-only attribution)');
await page.locator('#media-input').setInputFiles(root+'/public/assets/synthetic-turbine.wav');
await page.waitForFunction(()=>document.querySelectorAll('.sound-card')[2]?.textContent.includes('Mulig lydtype'),{timeout:60000});
console.log('Turbine:',await page.locator('.sound-card').nth(2).textContent());
await page.locator('#catalog-input').setInputFiles(referencePath);
await page.setViewportSize({width:390,height:844});await page.screenshot({path:root+'/test-output/multi-sound-mobile.png',fullPage:true});
if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1))throw Error('Mobile overflow');
await page.goto(base);await page.getByRole('button',{name:'Prøv demoen',exact:true}).click();
await page.locator('#results').waitFor({timeout:90000});
await page.locator('.source-panel .source-credit').waitFor({timeout:10000});
console.log('Flight result:',(await page.locator('.flight-checks').textContent()).slice(0,450));
await page.setViewportSize({width:1440,height:1000});await page.screenshot({path:root+'/test-output/multi-flight-results.png',fullPage:true});
if(errors.length)throw Error(errors.join('\n'));
await writeFile(root+'/test-output/multi-sound-browser.json',JSON.stringify({passed:true,checks:['bell screening','real catalog loading','local reference enrollment/export/import/match','turbine screening','mobile no overflow','flight demo with extra diagnostics'],pageErrors:errors},null,2));
await browser.close();
